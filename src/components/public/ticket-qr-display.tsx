"use client";

import { useRef } from "react";
import { Expand, X } from "lucide-react";
import "./ticket-qr-display.css";

export function TicketQrDisplay({
  qr,
  code,
  title,
}: {
  qr: string;
  code: string;
  title: string;
}) {
  const dialog = useRef<HTMLDialogElement>(null);
  return (
    <div className="entry-qr-display">
      {/* The QR stays private and is generated by the authenticated server page. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={qr} width={240} height={240} alt="Your signed entry QR code" />
      <strong className="m-mono">{code}</strong>
      <button
        type="button"
        className="r-quiet-button"
        onClick={() => dialog.current?.showModal()}
      >
        <Expand size={17} aria-hidden="true" /> Full-screen QR
      </button>
      <dialog ref={dialog} className="entry-qr-dialog" aria-labelledby="entry-qr-title">
        <button
          type="button"
          className="r-quiet-button entry-qr-close"
          aria-label="Close full-screen QR"
          onClick={() => dialog.current?.close()}
          autoFocus
        >
          <X size={20} aria-hidden="true" /> Close
        </button>
        <div className="entry-qr-content">
          <p className="m-eyebrow">YOUR WAY IN</p>
          <h2 id="entry-qr-title">{title}</h2>
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={qr} width={480} height={480} alt="Your entry QR code for scanning" />
          <strong className="m-mono">{code}</strong>
          <p>One guest per ticket. Show this screen to entry staff.</p>
          <small>Turn up your screen brightness if the scanner has trouble reading it.</small>
        </div>
      </dialog>
    </div>
  );
}
